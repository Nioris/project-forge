#!/usr/bin/env node
/** Keep dashboard build metadata aligned with the actual Forge distribution. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILE = path.join(ROOT, 'dashboard.html');
const CHECK = process.argv.includes('--check');

function dirs(p) { return fs.readdirSync(p, { withFileTypes: true }).filter(e => e.isDirectory()).map(e => e.name).sort(); }
const plugin = JSON.parse(fs.readFileSync(path.join(ROOT, '.claude-plugin', 'plugin.json'), 'utf8'));
const canonical = dirs(path.join(ROOT, '.claude', 'skills'));
const codex = dirs(path.join(ROOT, '.agents', 'skills'));
const commandNames = fs.readdirSync(path.join(ROOT, '.claude', 'commands')).filter(f => f.endsWith('.md')).map(f => f.replace(/\.md$/,'')).sort();
const skillNames = [...new Set([...canonical, ...commandNames])].sort();
const meta = {
  version: plugin.version,
  canonicalSkills: canonical.length,
  codexSkills: codex.length,
  routerSkills: codex.length - canonical.length,
  skillNames,
};
const block = `/* FORGE_META_START — generated by scripts/sync-dashboard-meta.mjs */\nvar FORGE_META=${JSON.stringify(meta)};\n/* FORGE_META_END */`;

function syncText(input) {
  let s = input;
  if (/\/\* FORGE_META_START[\s\S]*?\/\* FORGE_META_END \*\//.test(s)) {
    s = s.replace(/\/\* FORGE_META_START[\s\S]*?\/\* FORGE_META_END \*\//, block);
  } else {
    s = s.replace('<script>\n', `<script>\n${block}\n`, 1);
  }
  s = s.replace(/Dashboard · v\d+\.\d+\.\d+/g, `Dashboard · v${meta.version}`);
  s = s.replace(/Quick start \(v\d+\.\d+\.\d+\)/g, `Quick start (v${meta.version})`);
  s = s.replace(/Все доступные skills \(для power users\) — [^<]+/, `Все доступные skills (для power users) — ${meta.canonicalSkills} canonical / ${meta.codexSkills} Codex`);
  s = s.replace(/const PH_VER='v[^']+';/, `const PH_VER='v${meta.version}';`);
  return s;
}

const current = fs.readFileSync(FILE, 'utf8');
const expected = syncText(current);
if (CHECK) {
  if (current !== expected) {
    console.error('[X] dashboard metadata drift. Run: node scripts/sync-dashboard-meta.mjs');
    process.exit(1);
  }
  console.log(`[OK] dashboard metadata: v${meta.version}, ${meta.canonicalSkills} canonical skills, ${meta.codexSkills} Codex skills.`);
} else {
  fs.writeFileSync(FILE, expected, 'utf8');
  console.log(`[OK] dashboard metadata synced: v${meta.version}, ${meta.canonicalSkills} canonical, ${meta.codexSkills} Codex.`);
}
